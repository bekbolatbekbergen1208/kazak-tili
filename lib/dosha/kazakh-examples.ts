export function normalizeKazakhQuery(value: string) {
  const letters: Record<string, string> = {
    ә: "а",
    ғ: "г",
    қ: "к",
    ң: "н",
    ө: "о",
    ұ: "у",
    ү: "у",
    һ: "х",
    і: "и",
  };
  return value
    .toLocaleLowerCase("kk")
    .replace(/[әғқңөұүһі]/g, (letter) => letters[letter])
    .replace(/[^a-zа-яё0-9]+/giu, " ")
    .trim();
}

export function findKazakhExample(query: string) {
  const normalized = normalizeKazakhQuery(query);
  return kazakhExamples.find((example) =>
    example.questions.some(
      (question) => normalizeKazakhQuery(question) === normalized,
    ),
  );
}
