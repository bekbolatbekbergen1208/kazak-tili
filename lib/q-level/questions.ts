export const questionBank: Question[] = rows.map(
  ([skill, level, question, options, correct_answer, text_content], i) => ({
    id: `q-${i + 1}`,
    skill,
    level,
    type:
      skill === "listening"
        ? "audio"
        : skill === "grammar"
          ? "fill-blank"
          : "single-choice",
    question,
    options,
    correct_answer,
    text_content,
    difficulty: ["A1", "A2", "B1", "B2", "C1"].indexOf(level),
    tags: [skill, level],
    explanation: `Дұрыс жауап: ${correct_answer}. ${text_content ?? question}`,
  }),
);
export function productionQuestion(
  skill: "writing" | "speaking",
  level: Level,
): Question {
  const prompts: Record<Level, string> = {
    A0: "Өзің туралы 1–3 сөйлем құра.",
    A1: "Өзің және отбасың туралы 1–3 сөйлем құра.",
    A2: "Досыңа демалыс жоспарың туралы қысқа хабарлама жаз.",
    B1: "Туған қалаңда қонаққа қай жерді ұсынар едің? 80–120 сөзбен түсіндір.",
    B2: "Онлайн оқу мен сыныпта оқудың артықшылықтарын салыстырып, пікіріңді дәлелде.",
    C1: "Қаланың дамуы мен табиғи ортаны қорғаудың арасындағы тепе-теңдікті талдап, ұсыныс жаса.",
  };
  return {
    id: `${skill}-${level}`,
    skill,
    level,
    type: skill,
    question:
      skill === "speaking"
        ? {
            A0: "Өзің туралы айтып бер.",
            A1: "Өзің туралы айтып бер.",
            A2: "Күнделікті күніңді сипатта.",
            B1: "Қалаңа келген досыңа бір күндік саяхат жоспарын айтып бер.",
            B2: "Қоғамдық көлікті жақсарту туралы пікір білдір.",
            C1: "Тіл мен технологияның қоғамдағы рөлі туралы пікіріңді дәлелдермен қорға.",
          }[level]
        : prompts[level],
    difficulty: Math.max(0, ["A1", "A2", "B1", "B2", "C1"].indexOf(level)),
    tags: [skill, level],
  };
}
