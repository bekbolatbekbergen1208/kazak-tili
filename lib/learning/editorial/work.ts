export function enrichWork(l: Lesson): Lesson {
  if (l.goal !== "work") return l;
  const i = Number(l.id.split("-")[1]) - 1,
    r = rows[i];
  if (!r) return l;
  const [title, objective, text, example, targets, words] = r;
  return {
    ...l,
    title: { ...l.title, ru: title, en: title },
    slug: l.id,
    level: i < 5 ? "A1" : "A2",
    order: i + 1,
    status: "published",
    minutes: 8,
    topic: "Жұмыс орнындағы тіл",
    objective,
    introduction: text,
    explanation:
      "Қажетті ақпаратты нақты айтып, сыпайы тіркесті қолдан. Өз жауабыңды осы сабақтың үлгісімен салыстыр.",
    vocabulary: words.map((w, index) => ({
      ...wordEntry(w),
      id: `content:${l.id}:${index}`,
    })),
    reviewWords: words.map((w) => w.split("|")[0]),
    prerequisites: i === 0 ? [] : [`work-${i}`],
    dialogue: [
      { speaker: "Досша", text: "Осы жағдай туралы өзің не айтар едің?" },
      { speaker: "Оқушы", text: example },
    ],
    exercises: [
      ...l.exercises,
      {
        id: `${l.id}-apply`,
        kind: "open",
        prompt: { ru: objective, en: objective },
        answer: example,
        response: { minWords: 3, targetWords: targets.split(",") },
        objective,
        explanation: {
          ru: `Үлгі: ${example} Тексеру сөз саны мен мақсатты сөзді ғана қарайды.`,
          en: `Үлгі: ${example} Тексеру сөз саны мен мақсатты сөзді ғана қарайды.`,
        },
        translation: { ru: example, en: example },
        example,
      },
    ],
  };
}
