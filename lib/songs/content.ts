function lesson(
  data: Omit<SongLesson, "lyrics" | "tasks" | "checks"> & {
    lines: string[];
    gap: [string, string[], string, string];
    order: string[];
    listen: [string, string[], string, string];
    timings?: { start: number; end: number }[];
  },
): SongLesson {
  const { lines, gap, order, listen, timings, ...rest } = data;
  return {
    ...rest,
    lyrics: lines.map((text, i) => ({ text, ...timings?.[i] })),
    tasks: [
      {
        id: "gap",
        kind: "gap",
        prompt: gap[0],
        options: gap[1],
        answer: gap[2],
        explanation: gap[3],
        wordIds: [rest.words[0].id],
      },
      {
        id: "order",
        kind: "order",
        prompt: "Сөздерден табиғи сөйлем құра.",
        options: [...order].reverse(),
        answer: order,
        explanation: `Дұрыс рет: ${order.join(" ")}.`,
        wordIds: [rest.words[1].id],
      },
      {
        id: "match",
        kind: "match",
        prompt: "Әр сөзге сәйкес мағынаны таңда.",
        options: rest.words
          .slice(0, 3)
          .map((x) => x.ru)
          .reverse(),
        answer: rest.words.slice(0, 3).map((x) => x.ru),
        pairs: rest.words
          .slice(0, 3)
          .map((x) => ({ word: x.word, meaning: x.ru })),
        explanation: "Сөзді оның осы сабақтағы мағынасымен байланыстырамыз.",
        wordIds: rest.words.slice(0, 3).map((x) => x.id),
      },
      {
        id: "listening",
        kind: "listening",
        prompt: listen[0],
        options: listen[1],
        answer: listen[2],
        explanation: listen[3],
        wordIds: [rest.words[0].id],
        line: 0,
      },
    ],
    checks: [
      { prompt: gap[0], options: gap[1], answer: gap[2], explanation: gap[3] },
      {
        prompt: `«${rest.words[1].word}» сөзінің мағынасы қандай?`,
        options: rest.words.slice(0, 3).map((x) => x.ru),
        answer: rest.words[1].ru,
        explanation: rest.words[1].example,
      },
    ],
  };
}
