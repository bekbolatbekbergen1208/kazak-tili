export function wordExamples(id: string) {
  const word = findWord(id);
  if (!word) return [];
  return (
    examples[word.id] ?? [
      word.example,
      `Бүгін «${word.word}» сөзін үйрендім.`,
      `«${word.word}» сөзінің мағынасын мысалмен түсіндірдім.`,
    ]
  );
}
