export const literaryWords: LiteraryWord[] = data.map(
  ([id, word, meaning, example, synonyms, antonyms, forms, level]) => ({
    id,
    word,
    base: word,
    meaning,
    simple: meaning,
    example,
    synonyms,
    antonyms,
    forms,
    level,
    related: synonyms,
  }),
);
export function findWord(id: string): LiteraryWord | undefined {
  if (id.startsWith("dict:")) return findWord(id.slice(5));
  const own = literaryWords.find(
    (w) => w.id === id || w.word.toLocaleLowerCase() === id.toLocaleLowerCase(),
  );
  if (own) return own;
  const known = visionWords.find((w) => w.id === id || w.kk === id);
  if (!known) {
    const lookup = id.startsWith("dict:") ? id.slice(5) : id;
    const entry =
      expandedVocabulary.find(
        (w) => w.kk.toLocaleLowerCase() === lookup.toLocaleLowerCase(),
      ) ??
      commonDictionary.find(
        (w) => w.kk.toLocaleLowerCase() === lookup.toLocaleLowerCase(),
      );
    if (!entry) return undefined;
    return {
      id: `dict:${entry.kk.toLocaleLowerCase()}`,
      word: entry.kk,
      base: entry.kk,
      meaning: `${entry.translation.ru} · ${entry.translation.en}`,
      simple: `Қазақша сөз: ${entry.kk}.`,
      example:
        "example" in entry
          ? String(entry.example)
          : `Бүгін «${entry.kk}» сөзін үйрендім.`,
      synonyms: [],
      antonyms: [],
      forms: [entry.kk],
      level: "A2",
      related: [],
    };
  }
  return {
    id: known.id,
    word: known.kk,
    base: known.kk,
    meaning: `${known.kk} — ${known.en} (${known.ru}).`,
    simple: `Қазақша атауы: ${known.kk}.`,
    example: known.easy,
    synonyms: [],
    antonyms: [],
    forms: [known.kk, known.plural],
    level: "A1",
    related: [known.category],
  };
}
export const dailyExpression = literaryWords.find((w) => w.id === "koz-ashyp")!;
