import { levels, type Level } from "../q-level/types";
import type { AgeGroup, Style } from "./types";
export function learnerLevel(value: unknown): Level {
  return typeof value === "string" && levels.includes(value as Level)
    ? (value as Level)
    : "A1";
}
export function chooseStyle(message: string, level: Level): Style {
  if (/ресми|өтініш|іскерлік|formal/i.test(message)) return "formal";
  if (["A0", "A1"].includes(level)) return "simple";
  if (/эссе|дәлел|ғылыми|үй тапсырма|грамматика|септік/i.test(message))
    return "academic";
  if (/көркем|әдеби|өлең|метафора/i.test(message))
    return level === "A2" ? "daily" : "literary";
  if (/әңгіме құра|оқиға|ертегі/i.test(message)) return "storytelling";
  if (/саяхат|дүкен|қонақ|көлік|дастарқан/i.test(message)) return "daily";
  return "friendly";
}
