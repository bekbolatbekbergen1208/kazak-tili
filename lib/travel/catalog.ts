function fillEmptyRegionCards(regions: Region[]) {
  for (const r of regions) {
    if (r.contentStatus === "ready") continue;
    const content = emptyRegionContent[r.id];
    if (!content) continue;
    const source = r.sources[0]?.url;
    const cardWithSource = (
      id: string,
      title: string,
      text: string,
      icon: string,
    ): Card => ({ id: `${r.id}-${id}`, title, text, icon, source });
    if (!r.nature.length)
      r.nature = [
        cardWithSource(
          "overview",
          r.capital ? `${r.capital} өңірі` : r.nameKk,
          content.summary,
          r.theme === "city" ? "city" : r.theme === "sea" ? "wave" : "mountain",
        ),
      ];
    if (!r.landmarks.length)
      r.landmarks = content.places
        .slice(0, 4)
        .map((place, i) =>
          cardWithSource(
            `place-${i}`,
            place,
            `${place} — ${r.nameKk} туралы қысқа саяхат картасындағы маңызды орын.`,
            /кесене|музей|мұражай|орталық|қалашық/.test(place)
              ? "monument"
              : /көл|өзен|жағалау/.test(place)
                ? "wave"
                : "mountain",
          ),
        );
    if (!r.history.length)
      r.history = [
        cardWithSource(
          "story",
          r.type === "city" ? "Қала тарихы" : "Өңір тарихы",
          `${content.places[0]} арқылы ${r.nameKk} тарихы мен күнделікті өмірін тануға болады.`,
          "book",
        ),
      ];
    if (!r.animals.length)
      r.animals = [
        {
          ...cardWithSource(
            "wildlife",
            "Табиғатты бақылау",
            `${r.nameKk} табиғатын зерттегенде құстарды, жануарларды және олардың мекенін қорғау маңызды. Саяхатта шу шығармай, табиғи ортаға зиян келтірме.`,
            "bird",
          ),
          status:
            "Оқу карточкасы: нақты түрлер туралы толық дерек тексерілуде.",
        },
      ];
    if (!r.culture.length)
      r.culture = [
        cardWithSource(
          "words",
          "Сөз арқылы таны",
          content.words.join("; ") + ".",
          "book",
        ),
      ];
    if (!r.resources.length && !r.industries.length && !r.agriculture.length)
      r.resources = [
        cardWithSource(
          "learn",
          "Өлкені зерттеу",
          `${content.quiz} Осы сұрақ арқылы өңір атауын, орталығын және маңызды орнын есте сақта.`,
          "train",
        ),
      ];
    if (!r.importance.length)
      r.importance = [
        cardWithSource(
          "importance",
          "Таны, үйрен, сақта",
          content.summary,
          "book",
        ),
      ];
    if (!r.interestingFacts.length)
      r.interestingFacts = [
        r.capital
          ? `Орталығы — ${r.capital}.`
          : "Республикалық маңызы бар қала.",
        ...content.places
          .slice(0, 4)
          .map((place) => `${place} осы өңірмен байланысты.`),
      ];
    r.mapObjects = r.mapObjects.map((o) => ({
      ...o,
      ...r.landmarks.find((c) => c.id === o.id),
    }));
  }
}

fillEmptyRegionCards(regions);
