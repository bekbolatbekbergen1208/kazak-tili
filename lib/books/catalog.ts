export function battleFor(b: ReadingBook): BattleQuestion[] {
  const others = readingBooks.filter((x) => x.id !== b.id);
  const choices = (correct: string, values: string[]) =>
    [...new Set([correct, ...values])].slice(0, 4);
  return [
    {
      id: "author",
      prompt: "Шығарманың авторы кім?",
      options: choices(
        b.author,
        others.map((x) => x.author),
      ),
      answer: b.author,
      explanation: `${b.title} — ${b.author}.`,
    },
    {
      id: "genre",
      prompt: "Карточкада қандай жанр көрсетілген?",
      options: choices(
        b.genre,
        others.map((x) => x.genre),
      ),
      answer: b.genre,
      explanation: b.genre,
    },
    ...b.characters.slice(0, 2).map((c, i) => ({
      id: `hero-${i}`,
      prompt: c.description,
      options: choices(c.name, [
        ...b.characters.map((x) => x.name),
        ...others[0].characters.map((x) => x.name),
      ]),
      answer: c.name,
      explanation: `${c.name}: ${c.description}.`,
    })),
    ...b.vocabulary.map((v, i) => ({
      id: `word-${i}`,
      prompt: `«${v.word}» сөзінің мағынасы қандай?`,
      options: choices(v.meaning, [
        ...b.vocabulary.map((x) => x.meaning),
        others[0].vocabulary[0].meaning,
      ]),
      answer: v.meaning,
      explanation: `${v.word}: ${v.meaning}.`,
    })),
    {
      id: "theme",
      prompt: "Оқу шолуында қандай негізгі тақырып белгіленген?",
      options: choices(
        b.theme,
        others.map((x) => x.theme),
      ),
      answer: b.theme,
      explanation: b.summary,
    },
    {
      id: "first",
      prompt: "Оқу шолуы қай бөлімнен басталды?",
      options: b.chapters.map((c) => c.title),
      answer: b.chapters[0].title,
      explanation: b.chapters[0].text,
    },
    {
      id: "last",
      prompt: "Оқу шолуының соңғы бөлімі қалай аталады?",
      options: b.chapters.map((c) => c.title),
      answer: b.chapters.at(-1)!.title,
      explanation: b.chapters.at(-1)!.text,
    },
  ];
}
